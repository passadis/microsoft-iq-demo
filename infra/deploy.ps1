<#
.SYNOPSIS
Deploys the Microsoft IQ demo infrastructure and writes ../.env from the outputs.

.EXAMPLE
./deploy.ps1 -ResourceGroup rg-iq-demo -BaseName contosoiq

.EXAMPLE
./deploy.ps1 -ResourceGroup rg-iq-demo -BaseName contosoiq -Location westeurope -DeployStorage
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string]$ResourceGroup,
    [Parameter(Mandatory)] [string]$BaseName,
    [string]$Location = 'swedencentral',
    [string]$PrincipalId,
    [switch]$DeployStorage,
    [switch]$SkipEnv
)

$ErrorActionPreference = 'Stop'
$BaseName = $BaseName.ToLowerInvariant()

$account = az account show --query '{name:name, id:id}' -o json 2>$null | ConvertFrom-Json
if (-not $account) {
    throw 'Not signed in. Run az login first.'
}
Write-Host "Subscription: $($account.name) ($($account.id))"

if (-not $PrincipalId) {
    $PrincipalId = az ad signed-in-user show --query id -o tsv
    Write-Host "Presenter principal: $PrincipalId (signed-in user)"
}

az group create --name $ResourceGroup --location $Location --output none

Write-Host "Deploying infra/main.bicep to '$ResourceGroup' in '$Location'..."
$outputsJson = az deployment group create `
    --resource-group $ResourceGroup `
    --name 'microsoft-iq-demo' `
    --template-file (Join-Path $PSScriptRoot 'main.bicep') `
    --parameters baseName=$BaseName principalId=$PrincipalId deployStorage=$($DeployStorage.IsPresent.ToString().ToLowerInvariant()) `
    --query properties.outputs -o json
if ($LASTEXITCODE -ne 0) {
    throw 'Deployment failed. Review the errors above.'
}
$outputs = $outputsJson | ConvertFrom-Json

Write-Host ''
Write-Host "Project endpoint     : $($outputs.foundryProjectEndpoint.value)"
Write-Host "Project resource ID  : $($outputs.foundryProjectResourceId.value)"
Write-Host "Model deployment     : $($outputs.modelDeploymentName.value)"
Write-Host "Search endpoint      : $($outputs.searchEndpoint.value)"
if ($outputs.storageAccountName.value) {
    Write-Host "Storage account      : $($outputs.storageAccountName.value) (container: demo-data)"
}

if ($SkipEnv) {
    Write-Host 'Skipped .env generation (-SkipEnv).'
    return
}

$envPath = Join-Path (Split-Path $PSScriptRoot -Parent) '.env'
if (Test-Path $envPath) {
    $backup = "$envPath.backup-$(Get-Date -Format yyyyMMdd-HHmmss)"
    Copy-Item $envPath $backup
    Write-Host "Existing .env backed up to $(Split-Path $backup -Leaf)."
}

@"
# Generated by infra/deploy.ps1 on $(Get-Date -Format s)
FOUNDRY_PROJECT_ENDPOINT=$($outputs.foundryProjectEndpoint.value)
FOUNDRY_PROJECT_RESOURCE_ID=$($outputs.foundryProjectResourceId.value)
FOUNDRY_MODEL_DEPLOYMENT=$($outputs.modelDeploymentName.value)
FOUNDRY_AGENT_NAME=contoso-service-intelligence-agent

AZURE_AI_SEARCH_ENDPOINT=$($outputs.searchEndpoint.value)
FOUNDRY_IQ_KNOWLEDGE_BASE=contoso-service-kb
FOUNDRY_IQ_CONNECTION_NAME=contoso-service-kb-mcp
STORAGE_ACCOUNT_NAME=$($outputs.storageAccountName.value)
EMBEDDING_MODEL_DEPLOYMENT=text-embedding-3-small

FOUNDRY_IQ_API_VERSION=2026-08-01-preview
FOUNDRY_CONNECTION_API_VERSION=2025-10-01-preview
"@ | Set-Content -Path $envPath -Encoding utf8

Write-Host "Wrote $envPath."
Write-Host ''
Write-Host 'Next steps:'
Write-Host '  1. python scripts/preflight.py'
Write-Host '  2. python scripts/create_knowledge_base.py   (uploads data + creates the knowledge base; needs -DeployStorage)'
Write-Host '  3. python scripts/create_connection.py'
Write-Host '  4. python scripts/create_agent.py'
Write-Host '  5. python scripts/run_demo.py'
